const { contextBridge, ipcRenderer } = require("electron");

function subscribe(channel, callback) {
  const listener = (_event, value) => callback(value);
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
}

contextBridge.exposeInMainWorld("voxiva", {
  initialProject: () => ipcRenderer.invoke("project:initial"),
  chooseProject: () => ipcRenderer.invoke("project:choose"),
  chooseContextFile: () => ipcRenderer.invoke("project:context-file"),
  workspaces: () => ipcRenderer.invoke("workspace:list"),
  activateWorkspace: (cwd) => ipcRenderer.invoke("workspace:activate", cwd),
  createWorktree: (cwd, name) => ipcRenderer.invoke("workspace:create-worktree", cwd, name),
  mainWorktree: (cwd) => ipcRenderer.invoke("workspace:main-worktree", cwd),
  lastSession: (cwd) => ipcRenderer.invoke("workspace:last-session", cwd),
  sessions: () => ipcRenderer.invoke("session:list"),
  openSession: (id) => ipcRenderer.invoke("session:open", id),
  branch: (cwd) => ipcRenderer.invoke("project:branch", cwd),
  state: () => ipcRenderer.invoke("app:state"),
  platform: () => ipcRenderer.invoke("app:platform"),
  setWindowAppearance: (light) => ipcRenderer.invoke("window:appearance", light),
  preferences: () => ipcRenderer.invoke("app:preferences"),
  setPreferences: (input) => ipcRenderer.invoke("app:set-preferences", input),
  doctor: () => ipcRenderer.invoke("app:doctor"),
  commands: () => ipcRenderer.invoke("app:commands"),
  options: () => ipcRenderer.invoke("app:options"),
  checkUpdate: () => ipcRenderer.invoke("update:check"),
  downloadUpdate: () => ipcRenderer.invoke("update:download"),
  cancelUpdate: () => ipcRenderer.invoke("update:cancel"),
  openUpdate: () => ipcRenderer.invoke("update:open"),
  openRelease: () => ipcRenderer.invoke("update:open-release"),
  providerState: () => ipcRenderer.invoke("provider:state"),
  saveProvider: (input) => ipcRenderer.invoke("provider:save", input),
  removeProvider: (id) => ipcRenderer.invoke("provider:remove", id),
  setModel: (ref) => ipcRenderer.invoke("app:model", ref),
  setPlan: (id) => ipcRenderer.invoke("app:plan", id),
  newChat: () => ipcRenderer.invoke("chat:new"),
  sendChat: (prompt) => ipcRenderer.invoke("chat:send", prompt),
  stopChat: () => ipcRenderer.invoke("chat:stop"),
  applyEdits: (id) => ipcRenderer.invoke("chat:apply", id),
  discardEdits: (id) => ipcRenderer.invoke("chat:discard", id),
  start: (cwd) => ipcRenderer.invoke("terminal:start", cwd),
  write: (data) => ipcRenderer.send("terminal:write", data),
  resize: (cols, rows) => ipcRenderer.send("terminal:resize", cols, rows),
  onData: (callback) => subscribe("terminal:data", callback),
  onExit: (callback) => subscribe("terminal:exit", callback),
  onReply: (callback) => subscribe("chat:reply", callback),
  onSessionChanged: (callback) => subscribe("session:changed", callback),
  onWarning: (callback) => subscribe("chat:warning", callback),
  onUpdateProgress: (callback) => subscribe("update:progress", callback),
  onChunk: (callback) => subscribe("chat:chunk", callback),
  onReset: (callback) => subscribe("chat:reset", callback),
  onEdits: (callback) => subscribe("chat:edits", callback),
});
